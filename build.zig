const std = @import("std");

pub fn build(b: *std.Build) void {
    const target = b.standardTargetOptions(.{});
    const optimize = b.standardOptimizeOption(.{});
    const migrations = migrationsModule(b);

    const app = b.addExecutable(.{
        .name = "thing-for-doing-next",
        .root_module = appModule(b, target, optimize, migrations),
    });
    b.installArtifact(app);

    const run = b.addRunArtifact(app);
    run.step.dependOn(b.getInstallStep());
    if (b.args) |args| run.addArgs(args);
    const run_step = b.step("run", "Run the web server");
    run_step.dependOn(&run.step);

    const unit_tests = b.addTest(.{
        .root_module = appModule(b, target, optimize, migrations),
    });
    const test_step = b.step("test", "Run unit tests");
    test_step.dependOn(&b.addRunArtifact(unit_tests).step);
}

fn appModule(
    b: *std.Build,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
    migrations: *std.Build.Module,
) *std.Build.Module {
    const module = b.createModule(.{
        .root_source_file = b.path("src/main.zig"),
        .target = target,
        .optimize = optimize,
        .link_libc = true,
        .imports = &.{.{ .name = "migrations", .module = migrations }},
    });
    module.linkSystemLibrary("pq", .{});
    return module;
}

/// Builds a module exposing every `migrations/*.sql` file, embedded and sorted
/// by filename. Each migration's version is its filename without `.sql`.
fn migrationsModule(b: *std.Build) *std.Build.Module {
    const io = b.graph.io;
    var names: std.ArrayList([]const u8) = .empty;

    if (b.build_root.handle.openDir(io, "migrations", .{ .iterate = true })) |dir| {
        defer dir.close(io);
        var entries = dir.iterate();
        while (entries.next(io) catch |err| std.debug.panic("reading migrations/: {t}", .{err})) |entry| {
            if (entry.kind != .file or !std.mem.endsWith(u8, entry.name, ".sql")) continue;
            const version = entry.name[0 .. entry.name.len - ".sql".len];
            for (version) |char| switch (char) {
                'a'...'z', 'A'...'Z', '0'...'9', '_', '-' => {},
                else => std.debug.panic(
                    "migration '{s}' may only use letters, digits, '_' and '-' in its name",
                    .{entry.name},
                ),
            };
            names.append(b.allocator, b.dupe(entry.name)) catch @panic("OOM");
        }
    } else |err| switch (err) {
        error.FileNotFound => {},
        else => std.debug.panic("opening migrations/: {t}", .{err}),
    }

    std.mem.sort([]const u8, names.items, {}, struct {
        fn lessThan(_: void, lhs: []const u8, rhs: []const u8) bool {
            return std.mem.lessThan(u8, lhs, rhs);
        }
    }.lessThan);

    const files = b.addWriteFiles();
    var source: std.ArrayList(u8) = .empty;
    source.appendSlice(b.allocator,
        \\//! Generated by build.zig from migrations/*.sql.
        \\
        \\pub const Migration = struct {
        \\    version: []const u8,
        \\    sql: [:0]const u8,
        \\};
        \\
        \\pub const all = [_]Migration{
        \\
    ) catch @panic("OOM");
    for (names.items) |name| {
        _ = files.addCopyFile(b.path(b.fmt("migrations/{s}", .{name})), name);
        const version = name[0 .. name.len - ".sql".len];
        source.appendSlice(
            b.allocator,
            b.fmt("    .{{ .version = \"{s}\", .sql = @embedFile(\"{s}\") }},\n", .{ version, name }),
        ) catch @panic("OOM");
    }
    source.appendSlice(b.allocator, "};\n") catch @panic("OOM");

    return b.createModule(.{ .root_source_file = files.add("migrations.zig", source.items) });
}
